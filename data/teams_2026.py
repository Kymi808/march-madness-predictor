def _build_teams() -> list[TeamData]:
    """Convert raw dicts to TeamData objects."""
    teams = []
    for raw in _RAW_TEAMS:
        team = TeamData(**{k: v for k, v in raw.items() if hasattr(TeamData, k)})
        teams.append(team)
    return teams


_TEAMS_CACHE: list[TeamData] | None = None


def get_all_teams() -> list[TeamData]:
    """Get all 68 teams for the 2026 tournament."""
    global _TEAMS_CACHE
    if _TEAMS_CACHE is None:
        _TEAMS_CACHE = _build_teams()
    return list(_TEAMS_CACHE)


def get_team_by_name(name: str) -> TeamData | None:
    """Look up a team by name (case-insensitive)."""
    name_lower = name.lower()
    for team in get_all_teams():
        if team.name.lower() == name_lower:
            return team
    return None


def get_team_by_seed(seed: int, region: str) -> TeamData | None:
    """Look up a team by seed and region."""
    for team in get_all_teams():
        if team.seed == seed and team.region == region:
            return team
    return None
